void BoxGenerator::generateBoxes(int count) {
    if (!scene)
        return;
    std::shuffle(itemPositions.begin(), itemPositions.end(), *QRandomGenerator::global());

    int generated = 0;
    for (const QPoint& pos : itemPositions) {
        if (generated >= count)
            break;

        QRectF boxRect(pos, QSizeF(34, 35));
        bool overlaps = false;
        for (auto* item : scene->items(boxRect)) {
            QString type = item->data(0).toString();
            if (type == "barrier" || type == "ledge" || type == "sign" || type == "box") {
                overlaps = true;
                break;
            }
        }

        if (!overlaps) {
            QGraphicsPixmapItem* box = new QGraphicsPixmapItem(QPixmap(":/new/prefix1/box.png"));
            box->setPos(pos);
            box->setData(0, "box");
            box->setZValue(10);
            scene->addItem(box);
            generated++;
        }
    }
}
